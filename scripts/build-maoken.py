"""Convert pinned, unmodified Maoken hard-pen font to self-hosted SVG shards.
Usage: python3 scripts/build-maoken.py FONT.ttf OFL.txt
Source revision: 862082834f1f8686db122f20bebc69d2bd787467
Requires fontTools. Outlines retain their original shape and OFL license.
"""
import sys, json, hashlib, shutil
from pathlib import Path
from fontTools.ttLib import TTFont
from fontTools.pens.svgPathPen import SVGPathPen
source, license_path = map(Path, sys.argv[1:3])
raw = source.read_bytes()
assert hashlib.sha1(b'blob ' + str(len(raw)).encode() + b'\0' + raw).hexdigest() == '89a63f21573b8af7fe0f805ea7d2b727c2b823d6', 'Unexpected upstream font'
license_raw = license_path.read_bytes()
assert hashlib.sha1(b'blob ' + str(len(license_raw)).encode() + b'\0' + license_raw).hexdigest() == '6c5647d52d336690b8f0373e6bad9fe8e537b5c9', 'Unexpected upstream license'
font = TTFont(source)
glyphs = font.getGlyphSet()
blocks = {}
for code, name in sorted(font.getBestCmap().items()):
    if code < 32 or 127 <= code < 160:
        continue
    pen = SVGPathPen(glyphs, ntos=lambda v: format(round(v, 2), 'g'))
    glyphs[name].draw(pen)
    if not pen.getCommands():
        continue
    blocks.setdefault(code // 128, {})[chr(code)] = {'d': pen.getCommands(), 'a': font['hmtx'][name][0], 'u': font['head'].unitsPerEm}
out = Path('public/fonts/maoken')
out.mkdir(exist_ok=True)
for old in out.glob('*.json'):
    old.unlink()
for block, data in blocks.items():
    (out / f'{block}.json').write_text(json.dumps(data, ensure_ascii=False, separators=(',', ':')) + '\n')
shutil.copyfile(license_path, 'public/fonts/maoken-OFL.txt')
p = Path('public/fonts/manifest.json')
manifest = json.loads(p.read_text())
manifest['fonts']['maoken'] = {'glyphCount': sum(map(len, blocks.values())), 'blocks': sorted(blocks), 'family': 'MaokenYingBiKaiShuJ', 'version': '0.20', 'source': 'https://github.com/maoken-fonts/MaokenYingBiKaiShuJ/tree/862082834f1f8686db122f20bebc69d2bd787467', 'files': [{'file': 'MaokenYingBiKaiShuJ_0.20.ttf', 'sha256': hashlib.sha256(raw).hexdigest()}]}
p.write_text(json.dumps(manifest, ensure_ascii=False, indent=2) + '\n')
Path('src/font-coverage.js').write_text('// Generated by font build scripts\nexport const FONT_BLOCKS = ' + json.dumps({k:v['blocks'] for k,v in manifest['fonts'].items()}, separators=(',', ':')) + ';\n')
print(manifest['fonts']['maoken']['glyphCount'], 'glyphs;', len(blocks), 'blocks')
